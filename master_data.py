def get_branch_state(branch_name):
    if not branch_name:
        return 'Gujarat'
    b_upper = branch_name.strip().upper()
    for b in MASTER_BRANCHES:
        if b['name'] == b_upper:
            return b['state']
    if 'ANDHERI' in b_upper or 'MAHARASHTRA' in b_upper or 'MAHARASTRA' in b_upper:
        return 'Maharashtra'
    return 'Gujarat'

def match_master_vendor(vendor_name_query, gstin_query=""):
    """Fuzzy matches an extracted vendor name or partial GSTIN against the 91 master vendors."""
    if not vendor_name_query and not gstin_query:
        return None
        
    v_clean = "".join(e for e in (vendor_name_query or "").lower() if e.isalnum())
    g_clean = (gstin_query or "").strip().upper()

    # Exact GSTIN match
    if len(g_clean) == 15:
        for v in MASTER_VENDORS:
            if v["gstin"] == g_clean:
                return v

    # Substring / fuzzy vendor match
    best_match = None
    best_len = 0
    for v in MASTER_VENDORS:
        mv_clean = "".join(e for e in v["name"].lower() if e.isalnum())
        if mv_clean and (mv_clean in v_clean or v_clean in mv_clean):
            match_len = min(len(mv_clean), len(v_clean))
            if match_len > best_len:
                best_len = match_len
                best_match = v

    return best_match

def normalize_gstin(gstin_raw, vendor_name=""):
    """Cleans GSTIN string and if invalid/missing, checks master vendor directory."""
    if not gstin_raw or gstin_raw in ('N/A', '-', 'None', 'null'):
        if vendor_name:
            mv = match_master_vendor(vendor_name)
            if mv:
                return mv['gstin']
        return 'N/A'
    
    cleaned = re.sub(r'[^A-Za-z0-9]', '', str(gstin_raw)).upper()
    if len(cleaned) == 15:
        return cleaned
    
    # If not 15 chars, attempt master vendor match
    if vendor_name or cleaned:
        mv = match_master_vendor(vendor_name, cleaned)
        if mv:
            return mv['gstin']
            
    return cleaned if cleaned else 'N/A'

